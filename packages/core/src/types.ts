/** One finished 1Click swap as an outside observer can see it. */
export interface Flow {
  /** Unix seconds when the swap was created. */
  t: number;
  originAsset: string;
  destinationAsset: string;
  /** USD value of what went in, as reported by the Explorer API. */
  amountInUsd: number;
  /** USD value of what came out on the destination chain. */
  amountOutUsd: number;
  /** Human-readable origin amount (ZEC for zec-origin swaps). */
  amountIn: number;
  recipient: string;
  refundTo: string;
  status: string;
}

/** Visibility mode passed to 1Click as `confidentiality`. */
export type Confidentiality = "public" | "basic" | "advanced";

/** Where the ZEC for the deposit comes from. */
export type FundingSource =
  /** Straight from an Orchard/Sapling note to the 1Click deposit address. */
  | "shielded"
  /** From a transparent address the user has used before. */
  | "transparent-reused"
  /** From a transparent address that has never been used before. */
  | "transparent-fresh";

/** Where refunds and leftover input go. */
export type RefundMode =
  /** A transparent address the user already uses or has shielded from. */
  | "reused"
  /** A one-time address generated by Crowdline for this swap only. */
  | "one-time";

export interface SwapIntent {
  /** ZEC the user wants to send, as a decimal. */
  amountZec: number;
  /** ZEC/USD price used to translate the amount into the crowd's units. */
  zecUsd: number;
  destinationAsset: string;
  recipient: string;
  confidentiality: Confidentiality;
  funding: FundingSource;
  refund: RefundMode;
}

export interface CrowdOptions {
  /** Relative USD band an observer treats as "the same amount". 0.01 = ±1%. */
  band: number;
  /** Hours either side of the swap an observer would search. */
  windowHours: number;
  /** How far back to average activity, in hours. */
  lookbackHours: number;
}

export const DEFAULT_CROWD: CrowdOptions = {
  band: 0.01,
  // A payout lands a few minutes after its deposit, so an observer only has to
  // search a short window either side. ±15 minutes is generous to the user.
  windowHours: 0.25,
  lookbackHours: 24,
};

export interface Crowd {
  /** Matching zec-origin deposits per hour. */
  inPerHour: number;
  /** Matching outputs to the same destination asset per hour. */
  outPerHour: number;
  /**
   * Expected number of swaps, yours included, an observer could not tell
   * apart from yours inside the search window.
   */
  k: number;
  /** log2(k): how many bits of uncertainty the crowd gives you. */
  bits: number;
}

export type Severity = "critical" | "high" | "medium" | "low" | "ok";

export interface Finding {
  id: "ledger-link" | "amount" | "refund" | "funding" | "recipient";
  severity: Severity;
  title: string;
  detail: string;
  fix?: string;
}

export interface Report {
  intent: SwapIntent;
  crowd: Crowd;
  /** 0 (fully linkable) to 100 (best this route allows). */
  score: number;
  findings: Finding[];
}
